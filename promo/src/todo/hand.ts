// The duck's hand from ¡Al maíz! (mobile/src/features/rooms/grab/art.ts), copied
// here so the video draws the same hand; only the rounding is finer, since the
// video draws it much bigger than the game does.
const r2 = (v: number) => Math.round(v * 10000) / 10000;

type Pt = [number, number];

/** A closed curve through the points (Catmull-Rom). */
function curve(pts: Pt[]): string {
  const n = pts.length;
  let d = `M${r2(pts[0][0])} ${r2(pts[0][1])}`;
  for (let i = 0; i < n; i++) {
    const p0 = pts[(i - 1 + n) % n];
    const p1 = pts[i];
    const p2 = pts[(i + 1) % n];
    const p3 = pts[(i + 2) % n];
    d +=
      ` C${r2(p1[0] + (p2[0] - p0[0]) / 6)} ${r2(p1[1] + (p2[1] - p0[1]) / 6)}` +
      ` ${r2(p2[0] - (p3[0] - p1[0]) / 6)} ${r2(p2[1] - (p3[1] - p1[1]) / 6)}` +
      ` ${r2(p2[0])} ${r2(p2[1])}`;
  }
  return d + 'Z';
}

