/** Below this the hand is all arm: a tube that grows to reach. */
const WRIST = 0.42;

/** The hand's width as a share of its own drawing's height. */
export const HAND_W = HAND.w;

/**
 * The hand `len` drawings long (1: as drawn; more: a longer arm), in a box
 * HAND_W wide and `len` tall, fingers at the top. Paint `outer` black, then
 * `inner` in the hand's color, then `shade` dark and see-through.
 */
export function handPaths(len: number): { outer: string; inner: string; shade: string } {
  const k = (len - WRIST) / (1 - WRIST);
  const at = (pts: Pt[]): Pt[] => pts.map(([x, y]) => [x, y > WRIST ? WRIST + (y - WRIST) * k : y]);
  return {
    outer: curve(at(HAND.outer)),
    inner: curve(at(HAND.inner)),
    shade: curve(at(HAND.shade)),
  };
}

